'use strict';
const { AnalyzeRule, defaultSelect } = require('../src/core/rule');
const { parseHtml } = require('../src/core/dom');
const html = '<html><body><div class="row"><div>x1</div><span>s1</span></div><div class="row"><div>x2</div><span>s2</span></div></body></html>';
const doc = parseHtml(html);
const all = require('../src/core/selector');
console.log('all div:', all.selectAll(doc, 'div').length);
const nodes = defaultSelect(doc, 'class.row', null);
console.log('defaultSelect class.row ->', nodes.length, nodes.map((n) => n.className));
const nodes2 = defaultSelect(doc, 'class.row.-1', null);
console.log('class.row.-1 ->', nodes2.length);
const steps = require('../src/core/rule').parseDefaultRule('class.row.-1');
console.log('steps', JSON.stringify(steps));
const a = new AnalyzeRule({ content: html, baseUrl: 'http://x.com/' });
console.log('getElements class.row:', a.getElements('class.row').length);
console.log('getElements class.row.-1:', a.getElements('class.row.-1').length);
console.log('getElements tag.div:', a.getElements('tag.div').length);
console.log('getElements span:', a.getElements('span').length);
console.log('getString span@text:', JSON.stringify(a.getString('span@text')));
console.log('getString tag.div@text:', JSON.stringify(a.getString('tag.div@text')));
